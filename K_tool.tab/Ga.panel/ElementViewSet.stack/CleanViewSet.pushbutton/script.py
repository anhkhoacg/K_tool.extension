# -*- coding: utf-8 -*-
"""
Clean View Set

Delete views generated by "Element View Set"
(named <TypeName>_3D / PLAN / SEC1 / SEC2, optional _NN suffix),
and the VIEWS_ViewName_NOT CONTAINS_* filters no longer used by any view.
The list starts unticked: tick the views you want to delete.
"""

import re

from System.Collections.Generic import List

from pyrevit import revit, DB, forms, script


doc = revit.doc
uidoc = revit.uidoc
output = script.get_output()

NAME_PATTERN = re.compile(r"_(3D|PLAN|SEC1|SEC2)(_\d{2})?$")
MARKER_FILTER_PREFIX = "VIEWS_ViewName_NOT CONTAINS_"   # keep in sync with ElementViewSet


class ViewItem(forms.TemplateListItem):
    @property
    def name(self):
        return self.item.Name


generated = [
    v for v in DB.FilteredElementCollector(doc).OfClass(DB.View)
    if not v.IsTemplate and NAME_PATTERN.search(v.Name or "")
]

if not generated:
    forms.alert("No generated element views found.", exitscript=True)

generated.sort(key=lambda v: v.Name)
chosen = forms.SelectFromList.show(
    [ViewItem(v, checked=False) for v in generated],
    title="Delete generated element views",
    multiselect=True,
    button_name="Delete selected views",
)
if not chosen:
    script.exit()

active_id = doc.ActiveView.Id
if any(v.Id == active_id for v in chosen):
    forms.alert(
        "The active view is in the list. Switch to another view first.",
        exitscript=True)

deleted_views = 0
deleted_filters = 0

with revit.Transaction("Delete element view sets"):
    ids = List[DB.ElementId]([v.Id for v in chosen])
    deleted_views = len(chosen)
    doc.Delete(ids)

    # Remove VIEWS_ViewName_NOT CONTAINS_* filters no longer used by any view
    used = set()
    for view in DB.FilteredElementCollector(doc).OfClass(DB.View):
        try:
            for fid in view.GetFilters():
                used.add(fid.ToString())
        except Exception:
            pass

    unused = [
        f.Id for f in DB.FilteredElementCollector(doc)
        .OfClass(DB.ParameterFilterElement)
        if f.Name.startswith(MARKER_FILTER_PREFIX)
        and f.Id.ToString() not in used
    ]
    if unused:
        doc.Delete(List[DB.ElementId](unused))
        deleted_filters = len(unused)

forms.alert(
    "Deleted {} views and {} unused marker filters.".format(
        deleted_views, deleted_filters),
    title="Clean View Set", warn_icon=False)
